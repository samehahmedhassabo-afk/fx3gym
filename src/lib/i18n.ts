export type Locale = keyof typeof dictionaries;
export type Dictionary = (typeof dictionaries)["en"];

const typedDictionaries: Record<Locale, Dictionary> = dictionaries;

export async function getLocale(): Promise<Locale> {
  const cookieStore = await cookies();
  const locale = cookieStore.get("locale")?.value;
  return locale === "en" || locale === "ar" ? locale : "ar";
}

export async function getT(): Promise<{ t: Dictionary; locale: Locale; dir: "rtl" | "ltr" }> {
  const locale = await getLocale();
  return { t: typedDictionaries[locale], locale, dir: locale === "ar" ? "rtl" : "ltr" };
}
